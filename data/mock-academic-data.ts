export function formatAcademicDate(
  date: string,
  options?: Intl.DateTimeFormatOptions
) {
  return new Intl.DateTimeFormat(
    "en-KE",
    options ?? { weekday: "short", month: "short", day: "numeric" }
  ).format(new Date(date.includes("T") ? date : `${date}T12:00:00`));
}
